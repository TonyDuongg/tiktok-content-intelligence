-- Enable UUID extension for secure, non-enumerable IDs
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. USERS & AUTHENTICATION
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150),
    role VARCHAR(50) NOT NULL DEFAULT 'ROLE_USER', -- ROLE_USER, ROLE_ADMIN
    credits_balance INT NOT NULL DEFAULT 50,       -- Credit balance for scraping & AI script generation
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_email ON users(email);

-- 2. NICHES / CATEGORIES (e.g., Beauty, Fashion, Tech, Food, Storytelling)
CREATE TABLE categories (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. TIKTOK CHANNELS (Tracked / Ingested competitor channels)
CREATE TABLE tiktok_channels (
    id BIGSERIAL PRIMARY KEY,
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    tiktok_username VARCHAR(100) NOT NULL UNIQUE,  -- e.g., 'beauty_tips_vn' (without @)
    sec_uid VARCHAR(255),                          -- TikTok unique security UID
    nickname VARCHAR(150),                         -- Display nickname
    avatar_url TEXT,
    bio TEXT,
    followers_count BIGINT DEFAULT 0,
    total_likes BIGINT DEFAULT 0,
    total_videos INT DEFAULT 0,
    last_scraped_at TIMESTAMP WITH TIME ZONE,      -- Timestamp of most recent scraping
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_channels_username ON tiktok_channels(tiktok_username);
CREATE INDEX idx_channels_category ON tiktok_channels(category_id);

-- 4. TIKTOK VIDEOS (Ingested post & viral video data)
CREATE TABLE tiktok_videos (
    id BIGSERIAL PRIMARY KEY,
    channel_id BIGINT NOT NULL REFERENCES tiktok_channels(id) ON DELETE CASCADE,
    tiktok_video_id VARCHAR(100) NOT NULL UNIQUE,  -- Platform video ID
    video_url TEXT NOT NULL,
    cover_image_url TEXT,
    caption TEXT,                                  -- Post caption including hashtags
    hashtags TEXT[],                               -- Array of hashtag tokens
    
    -- Engagement Metrics
    view_count BIGINT DEFAULT 0,
    like_count BIGINT DEFAULT 0,
    comment_count BIGINT DEFAULT 0,
    share_count BIGINT DEFAULT 0,
    engagement_rate DECIMAL(6, 3) DEFAULT 0.000,   -- ((likes + comments + shares) / views) * 100
    
    -- Audio & Transcript for AI analysis
    duration_seconds INT,
    sound_title VARCHAR(255),
    transcript TEXT,                               -- Extracted audio transcript for LLM few-shot context
    
    video_published_at TIMESTAMP WITH TIME ZONE,   -- Original published timestamp on TikTok
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_videos_channel ON tiktok_videos(channel_id);
CREATE INDEX idx_videos_engagement ON tiktok_videos(engagement_rate DESC);
CREATE INDEX idx_videos_published_at ON tiktok_videos(video_published_at DESC);

-- 5. ASYNC JOBS (Background task coordinator with AWS SQS & Worker)
CREATE TABLE analysis_jobs (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    job_type VARCHAR(50) NOT NULL,                 -- 'SCRAPE_CHANNEL', 'ANALYZE_NICHE', 'GENERATE_SCRIPT'
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING', -- 'PENDING', 'QUEUED_SQS', 'PROCESSING', 'COMPLETED', 'FAILED'
    
    -- Filter params (Input filter JSON: niche, keyword, channels, min_views, date_range...)
    filter_params JSONB NOT NULL DEFAULT '{}'::jsonb,
    
    -- Cloud storage references
    s3_raw_data_url TEXT,                          -- S3 URI for durable raw JSON payload storage
    error_message TEXT,
    
    started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_jobs_user ON analysis_jobs(user_id);
CREATE INDEX idx_jobs_status ON analysis_jobs(status);

-- 6. AI SCRIPTS (Structured video scripts generated by LLM)
CREATE TABLE ai_scripts (
    id BIGSERIAL PRIMARY KEY,
    job_id UUID REFERENCES analysis_jobs(id) ON DELETE SET NULL,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    
    title VARCHAR(255) NOT NULL,
    target_audience VARCHAR(300),
    
    -- 3-Part viral short-video structure
    hook_3s TEXT NOT NULL,                         -- First 3 seconds verbal retention hook
    body_content TEXT NOT NULL,                    -- Core value & body script lines
    call_to_action TEXT NOT NULL,                  -- Final closing CTA
    
    visual_and_sound_cues TEXT,                    -- Director cues: camera angles, text overlays, b-roll
    suggested_hashtags TEXT[],
    estimated_duration_seconds INT DEFAULT 30,
    requested_duration_seconds INT CHECK (requested_duration_seconds BETWEEN 15 AND 600),
    
    ai_model_name VARCHAR(255) DEFAULT 'gemini-3.5-flash', -- Provider and model identifier used for generation
    status VARCHAR(30) DEFAULT 'DRAFT',            -- 'DRAFT', 'FAVORITE', 'EXPORTED'
    
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_scripts_user ON ai_scripts(user_id);
CREATE INDEX idx_scripts_category ON ai_scripts(category_id);

-- 7. SCRIPT REFERENCE VIDEOS (M:N Relationship: Viral source videos inspiring this script)
CREATE TABLE script_reference_videos (
    id BIGSERIAL PRIMARY KEY,
    script_id BIGINT NOT NULL REFERENCES ai_scripts(id) ON DELETE CASCADE,
    video_id BIGINT NOT NULL REFERENCES tiktok_videos(id) ON DELETE CASCADE,
    insight_note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_script_video UNIQUE(script_id, video_id)
);

-- ==============================================================================
-- INITIAL SEED DATA
-- ==============================================================================
CREATE TABLE research_profiles (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    own_username VARCHAR(24),
    target_audience VARCHAR(300) NOT NULL,
    offering VARCHAR(500),
    goal VARCHAR(500),
    keywords VARCHAR(1000) NOT NULL,
    excluded_keywords VARCHAR(1000),
    analytics_notes VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE video_observations (
    id BIGSERIAL PRIMARY KEY,
    video_id BIGINT NOT NULL REFERENCES tiktok_videos(id),
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    view_count BIGINT NOT NULL
);
CREATE INDEX idx_observation_video_time ON video_observations(video_id, observed_at);

